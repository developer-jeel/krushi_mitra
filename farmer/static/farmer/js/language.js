const LANGS = [{ code: "en", name: "English", flag: "🇬🇧" }, { code: "hi", name: "हिन्दी", flag: "🇮🇳" }, { code: "gu", name: "ગુજરાતી", flag: "🇮🇳" }, { code: "mr", name: "मराठी", flag: "🇮🇳" }, { code: "pa", name: "ਪੰਜਾਬੀ", flag: "🇮🇳" }, { code: "ta", name: "தமிழ்", flag: "🇮🇳" }, { code: "te", name: "తెలుగు", flag: "🇮🇳" }];

let currentLang = localStorage.getItem("km_lang") || "en";

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
}

function applyTranslations() {
  document.querySelectorAll("[data-translate]").forEach(el => {
    const key = el.getAttribute("data-translate");
    if (!key) return;

    // Handle specific attributes based on element tag or data-translate-attr
    const targetAttr = el.getAttribute("data-translate-attr");
    if (targetAttr) {
      el.setAttribute(targetAttr, t(key));
    } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.getAttribute("placeholder")) {
        el.placeholder = t(key);
      } else {
        el.value = t(key);
      }
    } else {
      // Find elements that contain text, replace it, preserving inner HTML like icons
      // Simpler approach: if the element has no children, set textContent
      // If it has children, we might need a specific structure. For now, replacing textContent or using data-translate carefully
      // Let's assume data-translate elements only hold the text to translate.
      el.textContent = t(key);
    }
  });

  const lbl = document.querySelector(".lang-current-label");
  if (lbl) {
    const l = LANGS.find(x => x.code === currentLang);
    if (l) lbl.textContent = l.name;
  }
  document.documentElement.lang = currentLang;
}

function setLang(code) {
  currentLang = code;
  localStorage.setItem("km_lang", code);
  applyTranslations();
  syncModalSelection(code);
}

function syncModalSelection(code) {
  document.querySelectorAll(".lang-item[data-lang]").forEach(el => {
    el.classList.toggle("selected", el.getAttribute("data-lang") === code);
  });
}

function buildLangModal() {
  const grid = document.getElementById("langGrid");
  if (!grid) return;
  grid.innerHTML = "";
  LANGS.forEach(l => {
    const div = document.createElement("div");
    div.className = "lang-item" + (l.code === currentLang ? " selected" : "");
    div.setAttribute("data-lang", l.code);
    div.innerHTML = `<span class="lang-flag">${l.flag}</span><span>${l.name}</span>`;
    div.addEventListener("click", () => {
      document.querySelectorAll(".lang-item[data-lang]").forEach(x => x.classList.remove("selected"));
      div.classList.add("selected");
    });
    grid.appendChild(div);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  buildLangModal();
  applyTranslations();

  const overlay = document.getElementById("langModal");
  document.querySelectorAll("[data-lang-trigger]").forEach(t => {
    t.addEventListener("click", () => overlay && overlay.classList.add("open"));
  });
  if (overlay) {
    overlay.addEventListener("click", e => {
      if (e.target === overlay) overlay.classList.remove("open");
    });
  }

  const applyBtn = document.getElementById("langApplyBtn");
  if (applyBtn) {
    applyBtn.addEventListener("click", () => {
      const sel = document.querySelector(".lang-item[data-lang].selected");
      if (sel) setLang(sel.getAttribute("data-lang"));
      overlay && overlay.classList.remove("open");
    });
  }
  const closeBtn = document.getElementById("langClose");
  if (closeBtn) closeBtn.addEventListener("click", () => overlay && overlay.classList.remove("open"));
});

